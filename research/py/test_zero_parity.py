"""Checks the TypeScript `rl-zero` bot's play path against the Python one.

    cd research
    npx tsx src/zeroParity.ts --decisions 400 [--logits --weights DIR] > zero-parity.jsonl
    python py/test_zero_parity.py zero-parity.jsonl [--checkpoint CKPT]

The weights were trained on what `tractor/nn/features.py` produces, and
evaluated through `eval/bots.py`: the engine's position rebuilt with
`state_from_wire`, encoded by `train/rollout.py::_pack`. The TS bot
encodes the engine's position itself, so the two must agree or the
shipped bot plays a different game from the one measured -- silently.

Features must be bit-identical: both sides do the same arithmetic on the
same integers and round to float16 the same way. Logits (with
``--checkpoint``) are compared against the PyTorch network with its
weights rounded to float16, as the export stores them; only the order of
accumulation differs, so a small tolerance is allowed, and the greedy
choice must agree except where the top two logits are within it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))

from tractor.eval.bots import state_from_wire  # noqa: E402
from tractor.nn.features import CONTEXT_DIM, D_CARD, HISTORY_DIM, NUM_PLANES, Cache, current_winner  # noqa: E402
from tractor.nn.model import ActorCritic, ModelConfig, load_model  # noqa: E402
from tractor.sim.actions import MoveSet  # noqa: E402
from tractor.train.buffer import obs_batch_from_arrays  # noqa: E402
from tractor.train.rollout import _InFlight, _pack  # noqa: E402

LOGIT_TOL = 2e-2


def _net(path: str) -> ActorCritic:
    blob = torch.load(path, map_location="cpu", weights_only=False)
    net = ActorCritic(ModelConfig(**blob["model_config"]))
    load_model(net, {k: v.to(torch.float16).to(torch.float32) if torch.is_floating_point(v) else v
                     for k, v in blob["model"].items()})
    return net.eval()


def write_fixture(dump: str, out: str, size: int) -> int:
    """A spread of positions (lead and follow, landlord or not, no-trump,
    early to late) with what the Python encoder makes of them."""
    recs = [json.loads(line) for line in open(dump)]
    picked: list[dict] = []
    seen: set[tuple] = set()
    for rec in recs:
        msg = rec["msg"]
        L = rec["ts"]["history_len"]
        key = (len(msg["trick_plays"]) > 0, msg["seat"] == msg["landlord"],
               msg["trump_suit"] == 4, min(L // 30, 3))
        if key in seen:
            continue
        seen.add(key)
        picked.append(msg)
        if len(picked) >= size:
            break
    cfg = ModelConfig()
    cache = Cache()
    cases = []
    for msg in picked:
        state = state_from_wire(msg)
        cands = [np.asarray(c, dtype=np.int8) for c in msg["candidates"]]
        p = _pack(_InFlight(state=state, episode=0), cache, cfg, moves=MoveSet(moves=cands))
        L = int(p.history_len)
        seat = int(msg["seat"])
        winner = current_winner(state)
        cases.append({
            "position": {
                "seat": seat, "levelRank": msg["level_rank"], "trumpSuit": msg["trump_suit"],
                "numDecks": msg["num_decks"], "landlord": msg["landlord"],
                "hand": msg["hands"][seat],
                "kitty": msg["kitty"] if seat == msg["landlord"] else None,
                "tricks": msg["tricks"], "trickPlays": msg["trick_plays"],
                "trickLeader": msg["trick_leader"],
                "currentWinner": winner,
            },
            "expected": {
                "historyLen": L,
                "history": p.history[:L].astype(np.float32).ravel().tolist(),
                "context": p.context.astype(np.float32).ravel().tolist(),
                "unseen": p.unseen.astype(np.float32).ravel().tolist(),
                "planes": p.planes.astype(np.float32).ravel().tolist(),
                "cards": p.cards.astype(np.float32).ravel().tolist(),
            },
        })
    with open(out, "w") as f:
        json.dump({"note": "generated by research/py/test_zero_parity.py --fixture", "cases": cases},
                  f, separators=(",", ":"))
    print(f"wrote {len(cases)} cases to {out}")
    return 0


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("dump")
    ap.add_argument("--checkpoint", default="")
    ap.add_argument("--fixture", default="",
                    help="write a small fixture of positions and the Python features "
                         "for packages/engine/test/zero-features.test.ts")
    ap.add_argument("--fixture-size", type=int, default=12)
    args = ap.parse_args(argv)
    if args.fixture:
        return write_fixture(args.dump, args.fixture, args.fixture_size)

    net = _net(args.checkpoint) if args.checkpoint else None
    cfg = net.cfg if net is not None else ModelConfig()
    cache = Cache()
    n = 0
    bad: dict[str, int] = {}
    max_err = 0.0
    argmax_same = argmax_total = 0
    hist_lens = []
    for line in open(args.dump):
        rec = json.loads(line)
        msg, ts = rec["msg"], rec["ts"]
        state = state_from_wire(msg)
        candidates = [np.asarray(c, dtype=np.int8) for c in msg["candidates"]]
        packed = _pack(_InFlight(state=state, episode=0), cache, cfg, moves=MoveSet(moves=candidates))
        L = int(packed.history_len)
        hist_lens.append(L)
        py = {
            "history_len": np.asarray([L]),
            "history": packed.history[:L].astype(np.float32).reshape(-1),
            "context": packed.context.astype(np.float32).reshape(-1),
            "unseen": packed.unseen.astype(np.float32).reshape(-1),
            "planes": packed.planes.astype(np.float32).reshape(-1),
            "cards": packed.cards.astype(np.float32).reshape(-1),
        }
        winner = current_winner(state)
        if (winner if winner is not None else -1) != (ts["current_winner"] if ts["current_winner"] is not None else -1):
            bad["current_winner"] = bad.get("current_winner", 0) + 1
        for key, want in py.items():
            got = np.asarray(ts[key] if key != "history_len" else [ts[key]], dtype=np.float32)
            if got.shape != want.shape or not np.array_equal(got, want):
                bad[key] = bad.get(key, 0) + 1
                if bad[key] == 1:
                    diff = (np.nonzero(got != want)[0][:8] if got.shape == want.shape else
                            f"shape {got.shape} vs {want.shape}")
                    print(f"first {key} mismatch at decision {n}: indices {diff}", file=sys.stderr)
                    if got.shape == want.shape:
                        idx = np.nonzero(got != want)[0][:4]
                        print(f"  ts {got[idx]} py {want[idx]}", file=sys.stderr)
        if net is not None and "logits" in ts:
            obs = obs_batch_from_arrays(
                packed.history[None], np.array([L], dtype=np.int64), packed.context[None],
                packed.unseen[None], packed.planes[None], packed.cards[None],
                packed.candidates[None], packed.candidate_mask[None], device="cpu")
            with torch.no_grad():
                out = net.actor(obs)
            k = len(candidates)
            want = out.logits[0, :k].float().numpy()
            got = np.asarray(ts["logits"], dtype=np.float32)
            err = float(np.max(np.abs(got - want)))
            max_err = max(max_err, err)
            if err > LOGIT_TOL:
                bad["logits"] = bad.get("logits", 0) + 1
            if k > 1:
                argmax_total += 1
                top2 = np.sort(want)[-2:]
                if int(np.argmax(got)) == int(np.argmax(want)) or top2[1] - top2[0] < LOGIT_TOL:
                    argmax_same += 1
        n += 1
    print(f"{n} decisions; history lengths {min(hist_lens)}..{max(hist_lens)}; "
          f"dims history {HISTORY_DIM} context {CONTEXT_DIM} cards {D_CARD} planes {NUM_PLANES}")
    if net is not None:
        print(f"logits: max abs error {max_err:.2e}; greedy choice agrees on "
              f"{argmax_same}/{argmax_total} multi-candidate decisions")
    if bad:
        print(f"MISMATCHES: {bad}")
        return 1
    print("features bit-identical" + ("; logits within tolerance" if net is not None else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
