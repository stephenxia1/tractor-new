"""The Python rules package against the TypeScript engine.

The fixtures under ``fixtures/`` are generated by ``research/src/
dumpOrdering.ts``, ``dumpCombos.ts`` and ``dumpFollow.ts``. They are
checked in so this suite runs without node; regenerate them whenever the
engine's rules change.

These are the tests that matter most in the package. Every other Python
test checks a property the implementation was written to satisfy; these
check it against a second implementation that was written independently
and has been played against for months.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from tractor.rules import cards as C
from tractor.rules import combos as K
from tractor.rules import follow as F

FIXTURES = Path(__file__).parent / "fixtures"

KIND_OF_NAME = {"single": K.SINGLE, "nkind": K.NKIND, "tractor": K.TRACTOR}


def _load(name: str) -> dict:
    path = FIXTURES / name
    if not path.exists():  # pragma: no cover - fixture is checked in
        raise RuntimeError(f"missing fixture {name}; regenerate with the TS dumpers")
    return json.loads(path.read_text())


def _encode(c: K.Component) -> tuple[int, int, int, int]:
    return (c.kind, c.top, c.length, c.n)


def _encode_engine(d: dict) -> tuple[int, int, int, int]:
    return (KIND_OF_NAME[d["kind"]], d["top"], d["length"], d["n"])


def test_ordering_tables_match_engine() -> None:
    """Effective suit and strength, all 54 types in all 65 contexts."""
    spec = _load("ordering.json")
    for row in spec["contexts"]:
        cid = C.context_id(row["levelRank"], row["trumpSuit"])
        np.testing.assert_array_equal(
            np.array(row["eff"], dtype=np.int8),
            C.EFF_SUIT[cid],
            err_msg=f"effective suit, level={row['levelRank']} trump={row['trumpSuit']}",
        )
        np.testing.assert_array_equal(
            np.array(row["strength"], dtype=np.int8),
            C.STRENGTH[cid],
            err_msg=f"strength, level={row['levelRank']} trump={row['trumpSuit']}",
        )


def test_classification_matches_engine() -> None:
    data = _load("combos.json")
    decks = data["decks"]
    for case in data["cases"]:
        ctx = C.Ctx(case["levelRank"], case["trumpSuit"])
        counts = C.counts_from_ids(case["slots"])
        mine = K.classify(counts, ctx, decks)
        engine = case["classified"]
        assert (None if mine is None else _encode(mine)) == (
            None if engine is None else _encode_engine(engine)
        ), f"classify {[C.card_name(s) for s in case['slots']]} in {ctx}"


def test_decomposition_matches_engine() -> None:
    """Compared as a multiset.

    When two runs tie on length the engine takes whichever its tractor
    search emitted first and this package takes the higher one. The
    components are the same either way, and nothing downstream reads
    their order.
    """
    data = _load("combos.json")
    decks = data["decks"]
    for case in data["cases"]:
        ctx = C.Ctx(case["levelRank"], case["trumpSuit"])
        counts = C.counts_from_ids(case["slots"])
        mine = K.decompose(counts, ctx, decks)
        engine = case["decomposed"]
        got = None if mine is None else sorted(_encode(x) for x in mine)
        want = None if engine is None else sorted(_encode_engine(x) for x in engine)
        assert got == want, f"decompose {[C.card_name(s) for s in case['slots']]} in {ctx}"


def test_follow_legality_matches_engine() -> None:
    data = _load("follow.json")
    decks = data["decks"]
    probes = 0
    for case in data["cases"]:
        ctx = C.Ctx(case["levelRank"], case["trumpSuit"])
        lead = C.counts_from_ids(case["lead"])
        hand = C.counts_from_ids(case["hand"])
        components = K.decompose(lead, ctx, decks)
        assert components is not None
        ob = F.lead_obligations(components, decks)
        lead_count = int(lead.sum())
        for probe in case["probes"]:
            cand = C.counts_from_ids(probe["cand"])
            mine = F.is_legal_follow(
                ob, lead_count, case["ledSuit"], cand, hand, ctx, decks
            )
            probes += 1
            assert mine == probe["ok"], (
                f"{ctx} led={case['ledSuit']} "
                f"lead={[C.card_name(s) for s in case['lead']]} "
                f"hand={[C.card_name(s) for s in case['hand']]} "
                f"cand={[C.card_name(s) for s in probe['cand']]}"
            )
    assert probes > 1000


def test_canonical_follow_is_always_legal() -> None:
    """A legal follow always exists, and this is one of them."""
    data = _load("follow.json")
    decks = data["decks"]
    for case in data["cases"]:
        ctx = C.Ctx(case["levelRank"], case["trumpSuit"])
        lead = C.counts_from_ids(case["lead"])
        hand = C.counts_from_ids(case["hand"])
        components = K.decompose(lead, ctx, decks)
        assert components is not None
        ob = F.lead_obligations(components, decks)
        lead_count = int(lead.sum())
        built = F.canonical_follow(ob, lead_count, case["ledSuit"], hand, ctx, decks)
        assert int(built.sum()) == lead_count
        assert not np.any(built > hand)
        assert F.is_legal_follow(
            ob, lead_count, case["ledSuit"], built, hand, ctx, decks
        )


def test_off_suit_level_pairs_do_not_chain() -> None:
    """Two off-suit level pairs share a rung, so they are not a tractor."""
    ctx = C.Ctx(C.RANK_NAMES.index("5"), 1)  # level 5, hearts trump
    five_s = C.card_id(0, C.RANK_NAMES.index("5"))
    five_d = C.card_id(2, C.RANK_NAMES.index("5"))
    assert ctx.strength[five_s] == ctx.strength[five_d] == 12
    counts = C.counts_from_ids([five_s, five_s, five_d, five_d])
    assert K.classify(counts, ctx, 2) is None
    parts = K.decompose(counts, ctx, 2)
    assert parts is not None
    assert [p.kind for p in parts] == [K.NKIND, K.NKIND]


def main() -> int:
    """Run every check. The repository's other Python tests are plain
    scripts, so this one is too; pytest collects it either way."""
    import time
    import sys

    fns = [v for k, v in sorted(globals().items()) if k.startswith("test_")]
    failed = 0
    for fn in fns:
        started = time.time()
        try:
            fn()
        except Exception as exc:  # noqa: BLE001 - reporting harness
            failed += 1
            print(f"FAIL  {fn.__name__}: {exc}"[:1200])
        else:
            print(f"ok    {fn.__name__}  ({time.time() - started:.1f}s)")
    print(f"{len(fns) - failed}/{len(fns)} passed")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
