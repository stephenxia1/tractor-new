"""Captures real decision records so benchmarks need no game engine.

A GPU benchmark box has no Node and no reason to have one, but records
generated by hand would not exercise the same code paths -- the featuriser
indexes by real card slots and trump contexts. So capture once here, where
the engine already runs, and ship the bytes.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from tractor_rl.features2 import merge_batches
from tractor_rl.protocol import WorkerConfig, WorkerPool

OUT = Path(__file__).resolve().parents[1] / "fixtures" / "records.npz"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--decisions", type=int, default=30000)
    ap.add_argument("--workers", type=int, default=3)
    ap.add_argument("--games", type=int, default=64)
    args = ap.parse_args()

    pool = WorkerPool(args.workers, WorkerConfig(
        games=args.games, seed=4242, learner_seats=15, privileged=True), num_groups=1)
    states, cands, owners, counts = [], [], [], []
    total = 0
    try:
        while total < args.decisions:
            bs = pool.read_round()
            m = merge_batches(bs)
            if m.num_decisions:
                states.append(m.states)
                cands.append(m.cands)
                owners.append(m.owner)
                counts.append(m.cand_counts)
                total += m.num_decisions
            pool.write_round(bs, [np.zeros(b.num_decisions, dtype=np.int64) for b in bs])
    finally:
        pool.close()

    OUT.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        OUT,
        states=np.concatenate(states)[: args.decisions],
        # Keep one batch's candidates intact: shapes must stay consistent
        # with their owners, so slicing across the join would corrupt them.
        cands=cands[0],
        owner=owners[0],
        cand_counts=counts[0],
    )
    z = np.load(OUT)
    print(f"wrote {OUT}")
    print(f"  states {z['states'].shape}  cands {z['cands'].shape}  "
          f"owner {z['owner'].shape}   {OUT.stat().st_size/1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
