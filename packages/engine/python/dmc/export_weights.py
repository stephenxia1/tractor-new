"""Convert a PyTorch training checkpoint into the TS-side embeddedWeights.ts.

Usage:
    python python/dmc/export_weights.py path/to/checkpoint.pt

Writes to src/rl/dmc/embeddedWeights.ts. Overwrites the existing
placeholder. Schema must match weights.ts SerializedWeights.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import torch

# Make `from dmc.foo` work regardless of cwd.
_SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(_SCRIPT_DIR.parent))

from dmc.constants import ROLES  # noqa: E402
from dmc.network import TripleQNet  # noqa: E402


# Mapping from PyTorch layer-name suffix → TS field name.
LAYER_MAP = [
    ('static_encoder.0.weight', 'staticW1'),
    ('static_encoder.0.bias',   'staticB1'),
    ('static_encoder.2.weight', 'staticW2'),
    ('static_encoder.2.bias',   'staticB2'),
    ('history_lstm.weight_ih_l0', 'lstmWi'),
    ('history_lstm.weight_hh_l0', 'lstmWh'),
    ('history_lstm.bias_ih_l0',   'lstmBi'),
    ('history_lstm.bias_hh_l0',   'lstmBh'),
    ('action_encoder.0.weight', 'actionW'),
    ('action_encoder.0.bias',   'actionB'),
    ('head.0.weight', 'headW1'),
    ('head.0.bias',   'headB1'),
    ('head.2.weight', 'headW2'),
    ('head.2.bias',   'headB2'),
    ('head.4.weight', 'headW3'),
    ('head.4.bias',   'headB3'),
]


def serialize_role(state_dict, role: str) -> dict:
    out = {}
    for pt_suffix, ts_name in LAYER_MAP:
        key = f'nets.{role}.{pt_suffix}'
        tensor = state_dict[key].detach().cpu().contiguous().view(-1)
        out[ts_name] = tensor.tolist()
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('checkpoint', type=str, help='Path to .pt file.')
    parser.add_argument(
        '--output',
        type=str,
        default=str(_SCRIPT_DIR.parent.parent / 'src' / 'rl' / 'dmc' / 'embeddedWeights.ts'),
    )
    args = parser.parse_args()

    print(f'Loading checkpoint: {args.checkpoint}')
    ck = torch.load(args.checkpoint, map_location='cpu', weights_only=False)
    state_dict = ck['state_dict']

    # Sanity: instantiate the network and load the dict so we surface key
    # mismatches loudly before serialization.
    net = TripleQNet()
    net.load_state_dict(state_dict, strict=True)

    payload = {
        'schema_version': 1,
        **{role: serialize_role(state_dict, role) for role in ROLES},
    }

    # Format as a single-line TS module — JSON.stringify is the most
    # compact while remaining valid TS literal syntax.
    json_text = json.dumps(payload)
    ts = (
        '// AUTO-GENERATED by python/dmc/export_weights.py — do not edit.\n'
        f'// Source: {Path(args.checkpoint).name}\n'
        f'// Episode: {ck.get("episode", "?")}\n'
        '\n'
        "import type { SerializedWeights } from './weights';\n"
        '\n'
        f'export const EMBEDDED_DMC_WEIGHTS: SerializedWeights = {json_text} as SerializedWeights;\n'
    )

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(ts, encoding='utf-8')
    size_mb = out_path.stat().st_size / (1024 * 1024)
    print(f'Wrote {out_path} ({size_mb:.1f} MB)')


if __name__ == '__main__':
    main()
